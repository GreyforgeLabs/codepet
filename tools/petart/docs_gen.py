"""Generated documentation: qml/assets/pets/PROVENANCE.md and docs/pets.md.

Both are derived from the committed manifests only (never from the source sheets), so
`extract.py --index` gives identical output with or without the sheets present.
"""

import json

import roster

ROUTE = ("GPT Image 2 (OpenAI image generation), run through the operator's ChatGPT "
         "subscription by the local Codex CLI image tool, with each sheet anchored on the "
         "species' PR #7 source sheet (`docs/art-library/source/…`, merged in v0.2.0)")

LICENCE = ("Distributed under the repository MIT licence (`qml/assets/pets/LICENSE`) by the "
           "project owner. The frames are AI-generated with OpenAI image generation; no "
           "third-party asset, asset pack, download or trace is included. Copyright and "
           "distribution suitability have not been legally reviewed.")


def _stage_names(m):
    return [s["name"] for s in m["stages"]]


def provenance_md(manifests, src_root=None):
    out = []
    w = out.append
    w("# Pet art provenance (v0.2.0)")
    w("")
    w("GENERATED by `tools/petart/extract.py --index`; do not edit by hand.")
    w("")
    w("## Summary")
    w("")
    w(f"- **Generation route:** {ROUTE}.")
    w(f"- **Licence:** {LICENCE}")
    w("- **Shipped form:** 192×192 lossy WebP (quality 86, alpha lossless) per pose, extracted "
      "from 4×3 chroma-key sheets by `tools/petart/extract.py` (chroma key with despill and "
      "fringe erode, connected-component cell split, one scale per species and stage, stage "
      "factors 0.82 / 0.92 / 1.0, ground line y = 184). Extraction is deterministic; "
      "`extract.py --check` rebuilds and byte-compares.")
    w("- **Source sheets are not in Git** (about 200 MB). They are to be attached to the v0.2.0 "
      "release as `codepet-art-sources-v0.2.tar`; every sheet's sha256 is listed below and in "
      "each `manifest.json` (`source.sheets`).")
    w("- **PR #7 library:** the 15 PR #7 sheets in `docs/art-library/` are the style anchors "
      "the v0.2 sheets were generated from (each species' reference hash is listed below). "
      "No PR #7 pixels are shipped directly.")
    w("- **Shared images:** `_placeholder.webp` and `_memorial.webp` are drawn with Pillow by "
      "`tools/petart/shared_art.py` (original, MIT).")
    w("- **Legacy art:** the ginger SVGs in `qml/assets/` keep their own `qml/assets/PROVENANCE.md`.")
    w("")
    for sid in roster.ORDER:
        m = manifests[sid]
        w(f"## {sid}")
        w("")
        w(f"{m['displayName']}, {m['personality']}. Stages: "
          + " / ".join(_stage_names(m)) + f" (names from {m.get('stageNamesSource', 'spec')}).")
        w("")
        src = m.get("source", {})
        if m.get("placeholder"):
            w("**Pending:** the six source sheets were not extracted yet; this species ships the "
              "neutral placeholder until `extract.py --species " + sid + "` runs.")
            w("")
            continue
        w(f"- Source directory: `{src.get('dir')}/` (planned release asset `codepet-art-sources-v0.2.tar`)")
        if src.get("generator"):
            w(f"- Generator (as recorded): {src['generator']}")
        ref = src.get("reference")
        if ref:
            w(f"- Style anchor: `{ref.get('file')}` sha256 `{ref.get('sha256')}`"
              + (f" ({ref.get('source')})" if ref.get("source") else ""))
        w("")
        w("| sheet | chroma | sha256 |")
        w("|---|---|---|")
        for s in src.get("sheets", []):
            w(f"| `{s['file']}` | `{s['chromaHex']}` | `{s['sha256']}` |")
        w("")
        notes = []
        for st in src.get("extraction", []):
            for sheet, o in sorted(st.get("sheetScales", {}).items()):
                desc = ", ".join(f"{k}={json.dumps(v)}" for k, v in sorted(o.items()) if k != "why")
                notes.append(f"- `{sheet}` sheet: {desc}. {o.get('why', '')}".rstrip())
            if st.get("keying"):
                o = st["keying"]
                desc = ", ".join(f"{k}={json.dumps(v)}" for k, v in sorted(o.items()) if k != "why")
                notes.append(f"- stage {st['stage']} keying (all sheets): {desc}. {o.get('why', '')}".rstrip())
            for cell, o in sorted(st.get("overrides", {}).items()):
                desc = ", ".join(f"{k}={json.dumps(v)}" for k, v in sorted(o.items()) if k != "why")
                notes.append(f"- stage {st['stage']} `{cell}`: {desc}. {o.get('why', '')}".rstrip())
        if notes:
            w("Extraction overrides (`tools/petart/overrides.json`):")
            w("")
            out.extend(notes)
            w("")
    return "\n".join(out).rstrip() + "\n"


def pets_md(manifests):
    out = []
    w = out.append
    ready = [sid for sid in roster.ORDER if not manifests[sid].get("placeholder")]
    w("# CodePet companions (v0.2.0)")
    w("")
    w("GENERATED by `tools/petart/extract.py --index` from the committed manifests; do not edit by hand.")
    w("")
    w(f"Extracted: **{len(ready)} of {len(roster.ORDER)}** species. "
      "Pending species carry `placeholder: true` and render `_placeholder.webp`; the release "
      "gate requires all 15 extracted (`test_pet_assets.py` without `CODEPET_ALLOW_PARTIAL_ART`).")
    w("")
    w("## Roster")
    w("")
    w("| id | name | default name | personality | habitat | young / grown / mature | locomotion |")
    w("|---|---|---|---|---|---|---|")
    for sid in roster.ORDER:
        m = manifests[sid]
        loco = m["locomotion"]
        w(f"| `{sid}` | {m['displayName']} | {m['defaultName']} | {m['personality']} | {m['habitat']} | "
          + " / ".join(_stage_names(m)) + f" | {loco['style']}, {loco['pxPerTick']} px/tick |")
    w("")
    w("Stage minimum levels: " + ", ".join(f"{k} L{v}" for k, v in zip(roster.STAGE_KEYS, roster.STAGE_MIN_LEVEL))
      + " (= `RULES_V1.stage_min_level`). Stage names come from each species' `provenance.json` "
      "when present, else SPEC §11.5.")
    w("")
    w("## Care labels")
    w("")
    w("| id | food | water | play | wash | bathroom | sleep |")
    w("|---|---|---|---|---|---|---|")
    for sid in roster.ORDER:
        c = manifests[sid]["careLabels"]
        w(f"| `{sid}` | " + " | ".join(c[k] for k in ("food", "water", "play", "wash", "bathroom", "sleep")) + " |")
    w("")
    w("Labels change wording only; every species has identical backend care effects.")
    w("")
    w("## Coverage matrix")
    w("")
    w("Each cell: states with frames present / 15, and distinct frame files for that stage.")
    w("")
    w("| id | stage 1 | stage 2 | stage 3 | thumbnails |")
    w("|---|---|---|---|---|")
    for sid in roster.ORDER:
        m = manifests[sid]
        files = m.get("files", {})
        cells = []
        for st in (1, 2, 3):
            have = 0
            for name, meta in m["states"].items():
                if all(f"s{st}/{f}" in files for f in meta["frames"]):
                    have += 1
            n = len([f for f in files if f.startswith(f"s{st}/")])
            cells.append("placeholder" if m.get("placeholder") else f"{have}/15 states, {n} frames")
        thumbs = sum(1 for st in (1, 2, 3) if f"thumb-s{st}.webp" in files)
        w(f"| `{sid}` | " + " | ".join(cells) + f" | {thumbs}/3 |")
    w("")
    w("## State → frame mapping (Amendment A4)")
    w("")
    w("Frames are files in `<id>/s<stage>/`: `bNN` from the base sheet, `cNN` from the care sheet.")
    w("")
    w("| state | frames | frameMs | mode | reducedFrame |")
    w("|---|---|---|---|---|")
    for name in roster.STATE_NAMES:
        t = roster.STATES[name]
        w(f"| {name} | {', '.join(t['frames'])} | {t['frameMs']} | {t['mode']} | {t['reducedFrame']} |")
    w("")
    custom = [(sid, name, fr) for sid in roster.ORDER
              for name, fr in roster.SPECIES[sid]["stateFrames"].items()]
    if custom:
        w("Per-species frame lists (same timing and mode): "
          + "; ".join(f"`{sid}` {name} = {', '.join(fr)}" for sid, name, fr in custom) + ".")
        w("")
    w("Base sheet cells: " + "; ".join(f"b{i:02d} {n}" for i, n in enumerate(roster.BASE_CELLS)) + ".")
    w("")
    w("Care sheet cells: " + "; ".join(f"c{i:02d} {n}" for i, n in enumerate(roster.CARE_CELLS)) + ".")
    w("")
    w("Frames face right. Floor species mirror when walking left; aquatic species (`goldfish`, "
      "`axolotl`) never mirror or roam: their habitat is fixed and `locomotion` swims inside it. "
      "Aquatic `water` blocks are geometric approximations of the jar/tank (`approximate: true`).")
    w("")
    w("## Regenerating")
    w("")
    w("```")
    w("python3 tools/petart/extract.py --status            # which species have six final sheets")
    w("python3 tools/petart/extract.py --species owl       # extract one species, then re-index")
    w("python3 tools/petart/extract.py --all               # every ready species, shared images, index")
    w("python3 tools/petart/extract.py --check             # rebuild in a scratch dir and byte-compare")
    w("python3 tools/petart/extract.py --contact           # QA contact sheets (run directory)")
    w("CODEPET_ALLOW_PARTIAL_ART=1 python3 qml/tests/test_pet_assets.py")
    w("python3 qml/tests/test_pet_distinctness.py")
    w("```")
    w("")
    w("Sources default to `~/Media/codepet-art/v0.2` (`--src` or `CODEPET_ART_SRC` to override). "
      "`*.reject-*.png` files are ignored; a species is ready only when all six sheets exist and "
      "match the sha256 values in its `provenance.json`. Fixes for individual cells (remap to "
      "another cell, horizontal flip, nudge, per-cell scale, fit exclusion, grounded hopper "
      "frame, source-sheet erase), per-sheet fixes (size scale, keying options, component "
      "reassignment) and species-wide keying options go in `tools/petart/overrides.json` with "
      "a reason; the reasons are copied into `PROVENANCE.md`.")
    w("")
    w("## Limits")
    w("")
    w("- Extraction quality was reviewed on contact sheets, not in the running overlay.")
    w("- **One shared timing table.** Issue #5 asks every type for its own key poses and "
      "timing, not the cat rig recoloured. v0.2 ships each species' own drawn poses (12 base "
      "and 12 care cells per stage), but every species plays them through the one A4 state "
      "table above: the same frame order, `frameMs` and mode, apart from the per-species frame "
      "lists noted there. Per-species pace exists only in locomotion (`pxPerTick`, pause "
      "ranges, hopper lift). Per-species idle and care timing and choreography (a slower "
      "capybara or turtle, quicker rabbit and frog beats) are deferred to a later pass that "
      "can review the motion in the running overlay.")
    w("- Sheet poses are generator output: frame-to-frame continuity of the locomotion "
      "cycles and care sequences is only as good as the sheets.")
    w("- Thin details thinner than one source pixel against the key (single whiskers) may be "
      "dropped by the despill and fringe erode.")
    w("- Floor poses are centred on the alpha centroid of their lowest 30 %; a pose too "
      "lopsided to centre that way (a leap, a long tail) is slid sideways just enough to stay "
      "inside the 2 px margin, so its feet may sit off-centre.")
    w("- The generator sometimes draws a stage's care sheet at a different character size than "
      "its base sheet; such sheets carry a measured `sheets` scale override (listed in "
      "`PROVENANCE.md`). Remaining size differences between poses come from the sheets.")
    w("- Hopper species (rabbit, frog, owl) keep the sheet's lift on locomotion frames; those "
      "frames are listed in `locomotion.airborneFrames` (and `states.locomotion.airborneFrames`) "
      "and exempt from the ground check.")
    w("- Aquatic habitats grow with the stage: `geometry.water.byStage` and "
      "`geometry.stageHitBoxes` give per-stage boxes; `geometry.water.outer` and `hitBox` are "
      "the union over all stages. Renderers should hit-test with the current stage's box.")
    w("- `geometry.pivot`, `propAnchor`, `badgeAnchor` and `water.swimBounds` (global and per "
      "stage) are recorded for later renderers; no v0.2 code reads them. "
      "`qml/tests/test_pet_assets.py` only checks that they are sane: the pivot on `groundY` for "
      "floor species, the anchors inside the canvas, and the swim bounds inside their water box "
      "and below its water line.")
    return "\n".join(out).rstrip() + "\n"
