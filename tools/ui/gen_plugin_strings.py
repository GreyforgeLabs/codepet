#!/usr/bin/env python3
"""Builds the bar plugin's copy table from the frozen contract docs/v0.3/contracts/strings.json
plus the WP5 additions in tools/ui/strings-wp5.json (keys the contract does not have yet;
an addition may never replace a contract key):
omarchy-plugin/strings.json (copy lint and tests read it) and omarchy-plugin/Strings.js (the
same table as a QML `.pragma library`, because the plugin cannot read files inside its own
folder at run time).

Run:   python3 tools/ui/gen_plugin_strings.py          (writes both files)
Check: python3 tools/ui/gen_plugin_strings.py --check  (exit 1 when either is stale)
Standard library only.
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "docs/v0.3/contracts/strings.json"
EXTRA = REPO / "tools/ui/strings-wp5.json"
PLUGIN = REPO / "omarchy-plugin"
HEADER = (".pragma library\n"
          "// Generated by tools/ui/gen_plugin_strings.py from docs/v0.3/contracts/strings.json and\n"
          "// tools/ui/strings-wp5.json. Do not edit: change those and regenerate. Every kid-facing\n"
          "// word lives here.\n")


def render_js(table: dict) -> str:
    body = json.dumps(table, indent=4, ensure_ascii=False)
    return HEADER + "var STRINGS = " + body + "\n"


def main(argv: list[str]) -> int:
    table = json.loads(SOURCE.read_text(encoding="utf-8"))
    extra = json.loads(EXTRA.read_text(encoding="utf-8"))
    clash = sorted(set(extra) & set(table))
    if clash:
        print(f"strings-wp5.json may only add keys; already in the contract: {clash}")
        return 1
    table.update(extra)
    raw = (json.dumps(table, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
    # The plugin and desktop are separate QML roots; keep their age rules identical.
    want = {PLUGIN / "strings.json": raw, PLUGIN / "Strings.js": render_js(table).encode("utf-8")}
    want[PLUGIN / "PetAge.js"] = (REPO / "qml/shared/PetAge.js").read_bytes()
    stale = [p for p, data in want.items() if not p.is_file() or p.read_bytes() != data]
    if "--check" in argv:
        for p in stale:
            print(f"stale: {p.relative_to(REPO)} (run tools/ui/gen_plugin_strings.py)")
        return 1 if stale else 0
    for p in stale:
        p.write_bytes(want[p])
        print(f"wrote {p.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
