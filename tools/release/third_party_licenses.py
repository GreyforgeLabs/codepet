#!/usr/bin/env python3
"""Write THIRD-PARTY-LICENSES.md: the licence notices of every crate linked into the
shipped `codepet` binary.

The crate set is read from `cargo metadata` for x86_64-unknown-linux-gnu: the normal
(runtime) dependency edges reachable from the `codepet` package. Build scripts' and dev
dependencies, and proc-macro crates (compile-time only) and their dependencies, are not
linked into the binary and are left out. Each crate's own LICENSE*/LICENCE*/COPYING*/
NOTICE*/UNLICENSE files are copied from its registry source; identical texts are printed
once. libsqlite3-sys compiles the bundled SQLite amalgamation, so SQLite's public-domain
dedication is included too.

    python3 tools/release/third_party_licenses.py            # rewrite THIRD-PARTY-LICENSES.md
    python3 tools/release/third_party_licenses.py --check    # exit 1 if it is out of date

Pass --offline (or set CARGO_NET_OFFLINE=true) to resolve from the local Cargo cache.
Python 3 standard library only.
"""
import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "THIRD-PARTY-LICENSES.md"
TARGET = "x86_64-unknown-linux-gnu"
ROOT_PACKAGE = "codepet"
LICENSE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")
SQLITE_NOTICE = """The author disclaims copyright to this source code.  In place of
a legal notice, here is a blessing:

   May you do good and not evil.
   May you find forgiveness for yourself and forgive others.
   May you share freely, never taking more than you give.

(SQLite is in the public domain: https://www.sqlite.org/copyright.html)"""


def metadata(offline):
    cmd = ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET]
    if offline:
        cmd.append("--offline")
    return json.loads(subprocess.run(cmd, cwd=REPO, check=True, capture_output=True, text=True).stdout)


def linked_packages(meta):
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    root = next(i for i in members if pkgs[i]["name"] == ROOT_PACKAGE)

    def proc_macro(pid):
        return any("proc-macro" in t["kind"] for t in pkgs[pid]["targets"])

    seen, todo = set(), [root]
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if not any(k["kind"] is None for k in dep["dep_kinds"]):
                continue
            if proc_macro(dep["pkg"]):
                continue
            todo.append(dep["pkg"])
    return sorted((pkgs[i] for i in seen if i not in members), key=lambda p: (p["name"], p["version"]))


def licence_files(pkg):
    root = Path(pkg["manifest_path"]).parent
    files = []
    for p in sorted(root.iterdir(), key=lambda p: p.name):
        if p.is_file() and p.name.upper().startswith(LICENSE_PREFIXES):
            files.append((p.name, p.read_text(errors="replace").strip("\n")))
    if not files and pkg.get("license_file"):
        p = root / pkg["license_file"]
        files.append((p.name, p.read_text(errors="replace").strip("\n")))
    return files


def render(pkgs):
    texts = {}  # sha -> (text, [crate labels])
    rows = []
    for pkg in pkgs:
        label = f"{pkg['name']} {pkg['version']}"
        refs = []
        files = licence_files(pkg)
        if pkg["name"] == "libsqlite3-sys":
            files.append(("SQLite (bundled amalgamation)", SQLITE_NOTICE))
        for name, text in files:
            sha = hashlib.sha256(text.encode()).hexdigest()[:12]
            texts.setdefault(sha, (text, []))[1].append(f"{label} ({name})")
            refs.append(f"[{name}](#text-{sha})")
        rows.append(f"| {pkg['name']} | {pkg['version']} | {pkg.get('license') or 'see text'} | "
                    f"{pkg.get('repository') or ''} | {', '.join(refs) if refs else 'none shipped by the crate'} |")
    out = [
        "# Third-party licences",
        "",
        "GENERATED by `tools/release/third_party_licenses.py`; do not edit by hand.",
        "",
        f"The `codepet` binary statically links the Rust crates below ({TARGET}, runtime "
        "dependencies only; build-time, proc-macro and test crates are not linked). Each "
        "crate's licence files are reproduced once below; CodePet itself is MIT "
        "(`LICENSE`). The pet art's licence is in `docs/licenses.md`.",
        "",
        "| crate | version | licence | repository | licence texts |",
        "|---|---|---|---|---|",
        *rows,
        "",
        "## Licence texts",
        "",
    ]
    for sha, (text, users) in sorted(texts.items(), key=lambda kv: kv[1][1][0]):
        out += [f'<a id="text-{sha}"></a>', f"### {users[0]}", ""]
        if len(users) > 1:
            out += ["Also the text of: " + "; ".join(users[1:]) + ".", ""]
        out += ["```text", text.replace("```", "'''"), "```", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if THIRD-PARTY-LICENSES.md is out of date")
    ap.add_argument("--offline", action="store_true", help="pass --offline to cargo metadata")
    args = ap.parse_args()
    import os
    offline = args.offline or os.environ.get("CARGO_NET_OFFLINE", "").lower() in ("1", "true", "yes")
    text = render(linked_packages(metadata(offline)))
    if args.check:
        if not OUT.is_file() or OUT.read_text() != text:
            print("THIRD-PARTY-LICENSES.md is out of date: run python3 tools/release/third_party_licenses.py",
                  file=sys.stderr)
            return 1
        print("THIRD-PARTY-LICENSES.md is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
